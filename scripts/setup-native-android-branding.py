#!/usr/bin/env python3
"""Use the repository's authentic Orvix icon in an isolated Capacitor QA APK.

The Android project is generated by Capacitor inside CI; no manual resource
editing survives the next 'cap add android'. Run AFTER 'cap sync android'.
Only changes app branding resources. Does NOT alter permissions, signing,
applicationId, data storage, network policy, or native functionality.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "public" / "brand" / "orvix-qa-logo.png"
RES = ROOT / "android" / "app" / "src" / "main" / "res"
MANIFEST = ROOT / "android" / "app" / "src" / "main" / "AndroidManifest.xml"

DENSITIES = {
    "mdpi": 1,
    "hdpi": 1.5,
    "xhdpi": 2,
    "xxhdpi": 3,
    "xxxhdpi": 4,
}
BRAND_BG = (255, 255, 255, 255)


def assert_project() -> None:
    if not SOURCE.is_file() or not RES.is_dir() or not MANIFEST.is_file():
        raise RuntimeError("Orvix icon or generated Android project is missing; run after cap sync android")


def render(source: Image.Image, size: int, content_fraction: float) -> Image.Image:
    if size < 48:
        raise ValueError("Android icon size is too small")
    canvas = Image.new("RGBA", (size, size), BRAND_BG)
    limit = max(1, round(size * content_fraction))
    mark = ImageOps.contain(source, (limit, limit), Image.Resampling.LANCZOS)
    canvas.alpha_composite(mark, ((size - mark.width) // 2, (size - mark.height) // 2))
    return canvas.convert("RGB")


def save_png(image: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, format="PNG", optimize=True)
    if not path.is_file() or path.stat().st_size < 200:
        raise RuntimeError(f"Generated empty Android branding asset: {path}")


def overwrite_app_name() -> None:
    strings = RES / "values" / "strings.xml"
    if not strings.is_file():
        raise RuntimeError("Capacitor Android app strings.xml was not generated")
    value = strings.read_text(encoding="utf-8")
    match = re.search(r"<string\s+name=['\"]app_name['\"][^>]*>.*?</string>", value, flags=re.S)
    if not match:
        raise RuntimeError("Cannot identify Android app_name string; refusing unsafe edit")
    value = value[:match.start()] + '<string name="app_name">Orvix</string>' + value[match.end():]
    strings.write_text(value, encoding="utf-8")


def replace_generated_brand_assets(source: Image.Image) -> None:
    # Delete generated Capacitor icons and splash images before creating their
    # replacements. Otherwise Android may select a stale density qualifier.
    for path in RES.rglob("*"):
        if not path.is_file():
            continue
        if path.parent.name.startswith(("mipmap-", "drawable")) and (
            path.stem in ("ic_launcher", "ic_launcher_round", "ic_launcher_foreground", "splash")
        ):
            path.unlink()

    for density, scale in DENSITIES.items():
        mipmap = RES / ("mipmap-" + density)
        icon_size = round(48 * scale)
        foreground_size = round(108 * scale)
        # Legacy launcher + round mask, with white background (no Capacitor art).
        icon = render(source, icon_size, 0.84)
        save_png(icon, mipmap / "ic_launcher.png")
        save_png(icon, mipmap / "ic_launcher_round.png")
        # Adaptive launcher safe area (~66% of 108dp viewport).
        save_png(
            render(source, foreground_size, 0.64),
            mipmap / "ic_launcher_foreground.png",
        )

    adaptive = RES / "mipmap-anydpi-v26"
    adaptive.mkdir(parents=True, exist_ok=True)
    xml = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/orvix_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        '</adaptive-icon>\n'
    )
    (adaptive / "ic_launcher.xml").write_text(xml, encoding="utf-8")
    (adaptive / "ic_launcher_round.xml").write_text(xml, encoding="utf-8")
    colors = RES / "values" / "orvix_branding.xml"
    colors.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<resources>\n'
        '    <color name="orvix_launcher_background">#FFFFFF</color>\n'
        '</resources>\n',
        encoding="utf-8",
    )

    # Capacitor Android versions use different drawable qualifiers for the
    # launch splash. Replace each generated splash, preserving its directory.
    # The launcher/app icon also covers Android 12 system splash fallbacks.
    drawable_folders = [
        path for path in RES.iterdir()
        if path.is_dir() and path.name.startswith("drawable")
    ]
    if not any(path.name == "drawable" for path in drawable_folders):
        drawable_folders.append(RES / "drawable")
    for folder in drawable_folders:
        if folder.name == "drawable":
            portrait = True
        else:
            portrait = "land" not in folder.name
        # Use a white, center-aligned Orvix logo. A generous border is
        # intentional so no mark gets clipped on tablet or phone launch.
        w, h = ((720, 1280) if portrait else (1280, 720))
        image = Image.new("RGBA", (w, h), BRAND_BG)
        mark = ImageOps.contain(source, (280, 280), Image.Resampling.LANCZOS)
        image.alpha_composite(mark, ((w - mark.width) // 2, (h - mark.height) // 2))
        save_png(image.convert("RGB"), folder / "splash.png")


def verify_outputs(source: Image.Image) -> None:
    for density, scale in DENSITIES.items():
        folder = RES / ("mipmap-" + density)
        for name in ("ic_launcher.png", "ic_launcher_round.png", "ic_launcher_foreground.png"):
            image_path = folder / name
            if not image_path.exists():
                raise RuntimeError(f"Missing branded icon: {image_path}")
            with Image.open(image_path) as actual:
                expected = round((108 if "foreground" in name else 48) * scale)
                if actual.size != (expected, expected):
                    raise RuntimeError(f"Incorrect icon dimensions: {image_path}")
    for name in ("ic_launcher", "ic_launcher_round"):
        xml = (RES / "mipmap-anydpi-v26" / (name + ".xml")).read_text()
        if "orvix_launcher_background" not in xml or "ic_launcher_foreground" not in xml:
            raise RuntimeError("Adaptive icon still points to generic Capacitor artwork")
    strings = (RES / "values" / "strings.xml").read_text()
    if '<string name="app_name">Orvix</string>' not in strings:
        raise RuntimeError("Android app label is not Orvix")
    splash_files = [p for p in RES.rglob("splash.*") if p.parent.name.startswith("drawable")]
    if not splash_files or any(p.suffix != ".png" for p in splash_files):
        raise RuntimeError("Unbranded Android launch splash resource remains")
    print(
        "Orvix native branding verified: "
        + str(len(DENSITIES)) + " launcher densities, "
        + str(len(splash_files)) + " splash variants, "
        + "source SHA-256 " + hashlib.sha256(SOURCE.read_bytes()).hexdigest()[:16]
    )


def main() -> int:
    assert_project()
    with Image.open(SOURCE) as image:
        image.load()
        if min(image.size) < 256:
            raise RuntimeError("Orvix source logo must be at least 256px for Android launcher quality")
        source = image.convert("RGBA")
    overwrite_app_name()
    replace_generated_brand_assets(source)
    verify_outputs(source)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as error:
        print(f"Orvix Android branding failed closed: {error}", file=sys.stderr)
        sys.exit(1)
